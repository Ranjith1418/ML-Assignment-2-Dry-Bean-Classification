import os
import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
import joblib
from sklearn.metrics import (accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, ConfusionMatrixDisplay, classification_report)

st.set_page_config(page_title="Dry Bean Classifier", page_icon="🫘", layout="wide")
MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib"
}

@st.cache_resource
def load_model(path):
    return joblib.load(path)

st.title("🫘 Dry Bean Classification Dashboard")
st.write("Upload labelled test data and evaluate one of the five saved classifiers. Models are not retrained here.")
choice = st.selectbox("Choose a model", list(MODEL_FILES))
file = st.file_uploader("Upload test CSV", type=["csv"])

if file is not None:
    try:
        data = pd.read_csv(file)
        if "Class" not in data.columns:
            st.error("CSV must contain the target column named Class.")
            st.stop()
        y_true = data["Class"].astype(str)
        X_test = data.drop(columns=["Class"])
        path = os.path.join("model", MODEL_FILES[choice])
        if not os.path.exists(path):
            st.error("Saved model not found: " + path)
            st.stop()
        model = load_model(path)
        expected = list(model.feature_names_in_) if hasattr(model, "feature_names_in_") else None
        if expected:
            missing = [c for c in expected if c not in X_test.columns]
            extra = [c for c in X_test.columns if c not in expected]
            if missing or extra:
                st.error(f"Feature mismatch. Missing: {missing}; unexpected: {extra}")
                st.stop()
            X_test = X_test[expected]
        pred = model.predict(X_test)
        prob = model.predict_proba(X_test)
        metrics = [
            ("Accuracy", accuracy_score(y_true, pred)),
            ("AUC (weighted OVR)", roc_auc_score(y_true, prob, multi_class="ovr", average="weighted", labels=model.classes_)),
            ("Precision (weighted)", precision_score(y_true, pred, average="weighted", zero_division=0)),
            ("Recall (weighted)", recall_score(y_true, pred, average="weighted", zero_division=0)),
            ("F1 (weighted)", f1_score(y_true, pred, average="weighted", zero_division=0)),
            ("MCC", matthews_corrcoef(y_true, pred))
        ]
        st.subheader("Evaluation Metrics — " + choice)
        cols = st.columns(3)
        for i, (label, value) in enumerate(metrics):
            cols[i % 3].metric(label, f"{value:.4f}")
        st.subheader("Confusion Matrix")
        fig, ax = plt.subplots(figsize=(9, 7))
        ConfusionMatrixDisplay.from_predictions(y_true, pred, labels=model.classes_,
            display_labels=model.classes_, xticks_rotation=45, cmap="Blues", ax=ax)
        plt.tight_layout()
        st.pyplot(fig)
        plt.close(fig)
        st.subheader("Classification Report")
        report = classification_report(y_true, pred, output_dict=True, zero_division=0)
        st.dataframe(pd.DataFrame(report).transpose(), use_container_width=True)
        output = data.copy()
        output["Predicted_Class"] = pred
        st.download_button("Download predictions CSV", output.to_csv(index=False).encode("utf-8"),
            "dry_bean_predictions.csv", "text/csv")
        with st.expander("Preview uploaded data"):
            st.dataframe(data.head(20), use_container_width=True)
    except Exception as e:
        st.error(f"Unable to evaluate CSV: {e}")
else:
    st.info("Upload test_data.csv generated by the training notebook. It must contain all 16 features and Class.")
